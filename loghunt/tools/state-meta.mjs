// Write image/state-meta.js: the snapshot's SHA-256 and size, which the page checks after downloading.
import fs from 'node:fs';
import { createHash } from 'node:crypto';

export function stateMeta(statePath) {
  const bytes = fs.readFileSync(statePath);
  return { sha256: createHash('sha256').update(bytes).digest('hex'), size: bytes.length };
}

export function writeStateMeta(statePath, outPath) {
  const { sha256, size } = stateMeta(statePath);
  fs.writeFileSync(outPath, `// Generated by tools/make-snapshot.mjs — do not edit.\nexport const STATE_SHA256 = '${sha256}';\nexport const STATE_SIZE = ${size};\n`);
}
