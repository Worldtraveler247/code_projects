// Regenerates specs.js from the Ansible installed on this machine:
//   node tools/build-specs.mjs
// Only facts are kept (option names, types, choices, defaults, aliases, which are required).
// No documentation text is copied.

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';

const MODULES = [
  'ansible.builtin.dnf', 'ansible.builtin.yum_repository', 'ansible.builtin.rpm_key',
  'ansible.builtin.service', 'ansible.builtin.systemd',
  'ansible.posix.firewalld',
  'community.general.parted', 'community.general.lvg', 'community.general.lvol',
  'community.general.filesystem', 'ansible.posix.mount',
  'ansible.builtin.copy', 'ansible.builtin.template', 'ansible.builtin.lineinfile',
  'ansible.builtin.blockinfile', 'ansible.builtin.file',
  'community.general.archive', 'ansible.builtin.unarchive',
  'ansible.builtin.cron', 'ansible.posix.at',
  'ansible.posix.selinux', 'ansible.posix.seboolean', 'community.general.sefcontext',
  'ansible.builtin.user', 'ansible.builtin.group', 'ansible.posix.authorized_key',
  'ansible.builtin.debug', 'ansible.builtin.setup', 'ansible.builtin.stat',
  'ansible.builtin.command', 'ansible.builtin.get_url',
];

const run = (command, args) => execFileSync(command, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], maxBuffer: 64 * 1024 * 1024 });

const specs = {};
for (const fqcn of MODULES) {
  const doc = Object.values(JSON.parse(run('ansible-doc', ['-j', fqcn])))[0].doc;
  const options = {};
  for (const name of Object.keys(doc.options || {}).sort()) {
    const source = doc.options[name];
    const option = { type: source.type || 'str' };
    if (source.required) option.required = true;
    if (Array.isArray(source.choices)) option.choices = source.choices.map(String);
    else if (source.choices && typeof source.choices === 'object') option.choices = Object.keys(source.choices);
    if (source.default !== undefined && source.default !== null && typeof source.default !== 'object') option.default = String(source.default);
    if (source.aliases) option.aliases = source.aliases;
    options[name] = option;
  }
  specs[fqcn] = { options };
}

const core = run('ansible', ['--version']).match(/core ([\d.]+)/)[1];
const collections = run('ansible-galaxy', ['collection', 'list']);
const version = (name) => collections.match(new RegExp(`^${name.replace('.', '\\.')}\\s+([\\d.]+)`, 'm'))[1];
const header = `// Generated by tools/build-specs.mjs. Do not edit by hand.
// Source: ansible-doc on ansible-core ${core}, ansible.posix ${version('ansible.posix')}, community.general ${version('community.general')}.

export const SOURCE = ${JSON.stringify({ core, posix: version('ansible.posix'), general: version('community.general') })};

export const SPECS = `;
writeFileSync(new URL('../specs.js', import.meta.url), `${header}${JSON.stringify(specs, null, 1)};\n`);
console.log(`${MODULES.length} modules written`);
