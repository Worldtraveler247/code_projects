// Records the error message Ansible really prints for each broken task in modules.js:
//   node tools/capture-faults.mjs
// Each task is run against localhost in check mode. A task with a bad argument fails during
// argument validation, before the module does any work, so nothing on this machine changes.
// A fault that carries its own `message` is not run: it cannot be reproduced off a RHEL host.

import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { MODULES } from '../modules.js';
import { SOURCE } from '../specs.js';

// Arguments changed only for this run. dnf needs a backend named on a machine without dnf.
// copy and template skip their module in check mode, so those two run for real, aimed at a
// scratch file; the bad argument still stops them before anything is written.
const scratch = mkdtempSync(join(tmpdir(), 'module-drill-out-'));
const EXTRA = {
  dnf: { use_backend: 'dnf4' },
  copy: { dest: join(scratch, 'copy.out') },
  template: { dest: join(scratch, 'template.out') },
};
const REAL_RUN = new Set(['copy', 'template']);
const LISTED = 6;

const cases = MODULES.flatMap((mod) => mod.faults.map((fault, n) => ({ mod, fault, n })).filter((entry) => !entry.fault.message));

function brokenArgs({ mod, fault }) {
  const args = { ...mod.args, ...(EXTRA[mod.id] || {}) };
  if (fault.kind === 'choice') args[fault.option] = fault.value;
  else if (fault.kind === 'missing') delete args[fault.option];
  else {
    args[fault.typo] = args[fault.option];
    delete args[fault.option];
  }
  return args;
}

const dir = mkdtempSync(join(tmpdir(), 'module-drill-'));
mkdirSync(join(dir, 'templates'));
mkdirSync(join(dir, 'files'));
writeFileSync(join(dir, 'templates', 'drill.conf.j2'), 'max_sessions=10\n');
// A made-up key with the right shape. It unlocks nothing.
writeFileSync(join(dir, 'files', 'drill.pub'), 'ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIDrillDrillDrillDrillDrillDrillDrillDrillDrillDr drill@example\n');

const tasks = cases.map((entry, i) => ({
  name: `case ${i}`,
  [entry.mod.fqcn]: brokenArgs(entry),
  ignore_errors: true,
  register: `r${i}`,
  ...(REAL_RUN.has(entry.mod.id) ? { check_mode: false } : {}),
}));
const report = cases.map((_, i) => ({ name: `report ${i}`, 'ansible.builtin.debug': { msg: `CASE ${i} >>> {{ r${i}.msg | default('NO MESSAGE') }}` } }));
const file = join(dir, 'faults.json');
// JSON is valid YAML, so the playbook needs no YAML writer.
writeFileSync(file, JSON.stringify([{ name: 'Capture fault messages', hosts: 'localhost', connection: 'local', gather_facts: false, tasks: [...tasks, ...report] }]));

let output = '';
try {
  output = execFileSync('ansible-playbook', ['--check', file], { cwd: dir, encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'], maxBuffer: 64 * 1024 * 1024 });
} catch (error) {
  output = `${error.stdout || ''}${error.stderr || ''}`;
}

function tidy(message) {
  // ansible-core 2.19 and later put "Task failed: " in front of an action plugin's message.
  let text = message.replace(/\\"/g, '"').replace(/^Task failed: /, '').replace(/(\\n)+/g, ' ').trim();
  const list = text.match(/^(.*Supported parameters include: )(.*?)\.?$/);
  if (list) {
    const names = list[2].replace(/ \(.*\)$/, '').split(', ');
    text = `${list[1]}${names.slice(0, LISTED).join(', ')}${names.length > LISTED ? ', ...' : '.'}`;
  }
  return text;
}

const messages = {};
cases.forEach((entry, i) => {
  const match = output.match(new RegExp(`CASE ${i} >>> (.*)"\\n`));
  if (!match) throw new Error(`No output for ${entry.mod.id} fault ${entry.n}`);
  (messages[entry.mod.id] ||= {})[entry.n] = tidy(match[1]);
});

writeFileSync(new URL('../messages.js', import.meta.url), `// Generated by tools/capture-faults.mjs. Do not edit by hand.
// Each message is what ansible-core ${SOURCE.core} printed for the matching fault in modules.js,
// with a long list of supported parameters cut to the first ${LISTED}.

export const MESSAGES = ${JSON.stringify(messages, null, 1)};
`);
console.log(`${cases.length} messages captured`);
