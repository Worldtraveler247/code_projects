// Regenerates docpages.js: what `ansible-doc -s` and `ansible-doc` print for each module, as text.
//   ANSIBLE_DOC=/path/to/ansible-doc node tools/build-docpages.mjs
// Point ANSIBLE_DOC at an ansible-core 2.14 install (the RHEL 9 version the exam and the lab use):
// 2.17 and later print a different layout, and the page teaches the layout you will see.
// Keeps, per module: the -s output word for word, and from the full page the line numbers of its
// sections and options plus the text of the options worth reading (required ones and one focus option).

import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { SPECS } from '../specs.js';
import { studySheet } from '../game.js';

const DOC = process.env.ANSIBLE_DOC || 'ansible-doc';
const run = (args) => execFileSync(DOC, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], maxBuffer: 16 * 1024 * 1024 });

const SECTION = /^([A-Z][A-Z ]+[A-Z])(?: \([^)]*\))?:/;
const OPTION = /^([=-]) (\w+)$/;

// The header names the module file by its absolute path on the machine that ran the tool. Keep
// only the part every install shares, from the ansible/ or ansible_collections/ directory down.
export function shortenHeader(line) {
  return line.replace(/\((?:\/[^()]*?\/)?((?:ansible_collections|ansible)\/[^()]*)\)/, '(…/$1)');
}

export function parsePage(text) {
  const lines = text.replace(/\s+$/, '').split('\n');
  const sections = [];
  const options = [];
  // RETURN VALUES lists its keys with the same `- name` lines, so only the OPTIONS section counts.
  let inOptions = false;
  lines.forEach((line, i) => {
    const section = line.match(SECTION);
    if (section) {
      sections.push({ line: i + 1, text: line });
      inOptions = section[1] === 'OPTIONS';
    }
    const option = line.match(OPTION);
    if (option && inOptions) options.push({ line: i + 1, required: option[1] === '=', name: option[2] });
  });
  return { lines, sections, options };
}

// One option's block: its `= name` or `- name` line down to the line before the next option or section.
export function optionBlock(lines, start) {
  const block = [lines[start - 1]];
  for (let i = start; i < lines.length; i += 1) {
    if (OPTION.test(lines[i]) || SECTION.test(lines[i])) break;
    block.push(lines[i]);
  }
  while (block.length && !block[block.length - 1].trim()) block.pop();
  return block.join('\n');
}

// The option to read in full: `state` when the examples use it, since its choices decide what a task
// does; otherwise, of the three the examples use most, the first with a list of choices, since choices
// and defaults are what -s leaves out. Failing that, the most used one.
export function focusOption(fqcn) {
  const spec = SPECS[fqcn].options;
  const ranked = studySheet(fqcn).common.filter((row) => !row.required);
  const pick = ranked.find((row) => row.name === 'state') || ranked.slice(0, 3).find((row) => spec[row.name].choices) || ranked[0];
  return pick ? pick.name : null;
}

if (process.argv[1] && import.meta.url.endsWith(process.argv[1].split('/').pop())) {
  const core = execFileSync(DOC, ['--version'], { encoding: 'utf8' }).match(/core ([\d.]+)/)[1];
  const out = {};
  for (const fqcn of Object.keys(SPECS)) {
    const short = run(['-s', fqcn]).replace(/\s+$/, '');
    const page = parsePage(run([fqcn]));
    const focus = focusOption(fqcn);
    const wanted = [...page.options.filter((option) => option.required).map((option) => option.name), ...(focus ? [focus] : [])];
    const blocks = {};
    for (const name of wanted) {
      const option = page.options.find((item) => item.name === name);
      if (option) blocks[name] = optionBlock(page.lines, option.line);
    }
    out[fqcn] = {
      short,
      header: shortenHeader(page.lines[0]),
      total: page.lines.length,
      sections: page.sections,
      options: page.options,
      focus: blocks[focus] ? focus : null,
      blocks,
    };
  }
  writeFileSync(new URL('../docpages.js', import.meta.url), `// Generated by tools/build-docpages.mjs. Do not edit by hand.
// Source: ansible-doc and ansible-doc -s on ansible-core ${core}, the version RHEL 9 ships.
// Ansible documentation is licensed GPL-3.0-or-later.

export const DOC_CORE = ${JSON.stringify(core)};

export const PAGES = ${JSON.stringify(out, null, 1)};
`);
  console.log(`${Object.keys(out).length} modules written from ansible-core ${core}`);
}
